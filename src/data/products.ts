import type { Product } from '@/types';

function variant(
    id: number,
    productId: number,
    opts: Partial<{
        sku: string;
        name: string | null;
        attributes: Record<string, string> | null;
        price: number;
        stockQuantity: number;
        reservedQuantity: number;
        isDefault: boolean;
        status: 'active' | 'inactive';
        imageIndex: number | null;
    }> = {},
) {
    return {
        id,
        productId,
        sku: opts.sku ?? `SKU-${id}`,
        name: opts.name ?? null,
        attributes: opts.attributes ?? null,
        price: opts.price ?? 499,
        stockQuantity: opts.stockQuantity ?? 20,
        reservedQuantity: opts.reservedQuantity ?? 0,
        isDefault: opts.isDefault ?? true,
        status: opts.status ?? ('active' as const),
        imageIndex: opts.imageIndex ?? null,
    };
}

function images(
    productId: number,
    slug: string,
    tones: string[],
    labels: string[],
) {
    return tones.map((tone, index) => ({
        id: productId * 10 + index + 1,
        productId,
        tone,
        label: labels[index] ?? `View ${index + 1}`,
        altText: labels[index] ?? `Product ${productId} image ${index + 1}`,
        sortOrder: index,
        isPrimary: index === 0,
        src: `/images/products/${slug}-${index}.webp`,
    }));
}

