import type { Order, OrderStatus } from '@/types';

function guest(
    name: string,
    email: string,
    mobile: string,
    city: string,
    barangay: string,
    street: string,
) {
    return {
        fullName: name,
        email,
        mobile,
        city,
        barangay,
        street,
        province: 'Metro Manila',
        region: 'NCR',
    };
}

function history(
    entries: Array<{
        id: number;
        from: OrderStatus | null;
        to: OrderStatus;
        at: string;
        note?: string;
    }>,
) {
    return entries.map((e) => ({
        id: e.id,
        fromStatus: e.from,
        toStatus: e.to,
        note: e.note ?? null,
        createdAt: e.at,
    }));
}

